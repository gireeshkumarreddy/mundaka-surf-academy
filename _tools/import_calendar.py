"""Import the academy's class calendar PDF (one page per month, low tides and the two groups around each one) into
public/data/schedule.json, which the booking calendar reads.

    ~/.local/venvs/media/bin/python3 -I _tools/import_calendar.py <calendar.pdf> [season-from season-to]

Each month page lists, per day: "Bajamar HH:MM" followed by one or two group times "HH:MM-HH:MM" (2 h before / 2 h after
the low tide, cut to daylight). The page title gives the month ("Marzo 2027"). Checks every month is complete (all its days,
each with a time) and stops on anything it can't read, so a changed layout never fills the calendar with wrong times.
"""
import json
import re
import sys
from calendar import monthrange
from pathlib import Path

import fitz  # PyMuPDF

ROOT = Path(__file__).resolve().parent.parent
MONTHS = {m: i for i, m in enumerate(["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto",
                                       "septiembre", "octubre", "noviembre", "diciembre"], 1)}
TIDE = re.compile(r"^Bajamar (\d{2}:\d{2})$")
SLOT = re.compile(r"^(\d{2}:\d{2})-(\d{2}:\d{2})$")


def read(pdf):
    days = {}
    for page in fitz.open(pdf):
        lines = [l.strip() for l in page.get_text().splitlines() if l.strip()]
        title = re.match(r"^(\w+) (\d{4})$", lines[0])
        if not title or title.group(1).lower() not in MONTHS:
            sys.exit(f"page {page.number + 1}: no month title (got {lines[0]!r})")
        year, month = int(title.group(2)), MONTHS[title.group(1).lower()]
        count = monthrange(year, month)[1]
        day, current = 0, None
        for line in lines[1:]:
            if line.isdigit() and int(line) == day + 1 and day < count:
                day += 1
                current = days.setdefault(f"{year}-{month:02d}-{day:02d}", {"low": [], "slots": []})
            elif current is not None and (m := TIDE.match(line)):
                current["low"].append(m.group(1))
            elif current is not None and (m := SLOT.match(line)):
                if m.group(1) >= m.group(2):
                    sys.exit(f"{year}-{month:02d}-{day:02d}: impossible time {line}")
                current["slots"].append(line)
            elif line.startswith("Grupo 1"):
                break  # legend at the bottom of the page
        if day != count:
            sys.exit(f"{title.group(0)}: read {day} days, expected {count}")
    empty = [d for d, v in days.items() if not v["slots"] or not v["low"]]
    if empty:
        sys.exit(f"days without a tide or a time: {', '.join(empty)}")
    for v in days.values():
        v["slots"].sort()
    return days


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    days = read(sys.argv[1])
    first, last = min(days), max(days)
    season = {"from": sys.argv[2], "to": sys.argv[3]} if len(sys.argv) > 3 else {"from": first, "to": last}
    out = ROOT / "public" / "data" / "schedule.json"
    data = {
        "$comment": (
            "Booking calendar: the season and each day's lesson times, set by the tide (the academy's calendar: two "
            "groups per low tide, 2 h before and 2 h after, daylight only). days: { \"YYYY-MM-DD\": { \"low\": [\"HH:MM\"], "
            "\"slots\": [\"HH:MM-HH:MM\"], \"closed\": true } }. A season day without an entry can still be booked: the "
            "time is confirmed later. Generated by _tools/import_calendar.py from the academy's PDF; edit a day by hand "
            "if the school changes it."
        ),
        "season": season,
        "days": days,
    }
    # one line per day: easy to read and edit by hand
    rows = ",\n".join(f'    "{k}": {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(days.items()))
    out.write_text(
        "{\n"
        f'  "$comment": {json.dumps(data["$comment"], ensure_ascii=False)},\n'
        f'  "season": {json.dumps(season)},\n'
        f'  "days": {{\n{rows}\n  }}\n'
        "}\n"
    )
    slots = sum(len(v["slots"]) for v in days.values())
    print(f"{len(days)} days ({first} → {last}), {slots} class times → {out.relative_to(ROOT)}")


main()
